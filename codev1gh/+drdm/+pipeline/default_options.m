function options = default_options()
%DEFAULT_OPTIONS 建立强径参照筛选与不确定度计算的默认参数。
%
% 输入：无。
% 输出：options：背景、搜索、模型选择、区间、预算和门限配置。
%
% reference_selection.mode 为 sequential 或 joint_model；uncertainty.method 为 information 或 independent_linearized。

background = drdm.statistics.default_options();
background = rmfield(background,{'bootstrap_payload_seeds','bootstrap_noise_seeds', ...
    'interval_probability','bootstrap_match_radius'});
search = drdm.estimation.default_options();
search.fit_mode = 'joint_conditional';
search.candidates_per_branch = 2;
search.refine_candidates = 16;
options = struct('version','drdm-sequential-v1','background',background,'search',search, ...
    'max_paths',4,'interval_multiplier',3,'max_delay_halfwidth_s',1e-7, ...
    'max_doppler_halfwidth_hz',5,'budget_y_points',[2e-6 100;2e-6 -100], ...
    'budget_signal_amplitudes',0.01,'max_prior_mse_fraction',0.1, ...
    'min_signal_to_total_error',10,'minimum_threshold',0,'development_threshold',0, ...
    'reference_selection',struct('mode','sequential','residual_cost_limit',1000, ...
    'reduced_optimizer',struct('finite_difference_type','central', ...
    'max_iterations',240,'max_function_evaluations',3200)), ...
    'uncertainty',struct('method','information', ...
    'payload_seeds',46001:46032,'noise_seeds',47001:47032));
end
