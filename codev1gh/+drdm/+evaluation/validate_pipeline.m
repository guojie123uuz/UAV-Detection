function certificate = validate_pipeline(calibration,dataset)
%VALIDATE_PIPELINE 以独立评价计算同时置信界并汇总验收。
%
% 输入：calibration：固定训练结果；dataset：独立 evaluation 数据。
% 输出：certificate：错误率、共同覆盖率、预算失败率及总体结果。
%
% 二项界采用 Clopper–Pearson 方法，多项指标采用 Bonferroni 校正。

assert(strcmp(dataset.role,'evaluation'),'drdm:DatasetRole','Final evidence must be independent evaluation data.');
assert(strcmp(calibration.prepared_id,dataset.prepared_id) && ...
    strcmp(calibration.procedure_id,dataset.procedure_id) && strcmp(calibration.suite_id,dataset.suite_id) && ...
    isequaln(calibration.threshold,dataset.threshold), ...
    'drdm:CalibrationMismatch','Evaluation code, population or threshold differs from frozen training.');
drdm.statistics.check_seed_sets(calibration.interval_calibration.all_seeds,calibration.all_seeds,dataset.all_seeds);
profiles = dataset.suite.profiles;
positive = arrayfun(@(p)~isempty(p.path_boxes),profiles);
% 按全部场景和指标分配总体显著性水平，即 Bonferroni 校正。
assertions = numel(profiles)+2*sum(positive);
confidence = 1-(1-dataset.suite.family_confidence)/assertions;
template = struct('name','','sample_count',0,'false_paths',[],'joint_coverage',[], ...
    'budget_failures',[],'passed',false,'incomplete_count',0,'missed_blocks',0);
reports = repmat(template,1,numel(profiles));
for k = 1:numel(profiles)
    records = dataset.records([dataset.records.profile_index]==k);
    n = numel(records);
    falseEvents = arrayfun(@(r)r.score.false_path_event || ~r.score.complete || r.score.false_count>0,records);
    falseBound = drdm.statistics.binomial_interval(sum(falseEvents),n,confidence);
    passed = falseBound.one_sided_upper<=dataset.suite.target_false_path_probability;
    coverage = [];
    budget = [];
    if positive(k)
        hits = arrayfun(@(r)r.score.joint_interval_coverage && r.score.joint_recovery && ...
            r.score.complete && r.score.false_count==0 && r.score.missed_count==0,records);
        failures = arrayfun(@(r)~r.score.budget_passed || ~r.score.complete || ...
            r.score.false_count>0 || r.score.missed_count>0,records);
        coverage = drdm.statistics.binomial_interval(sum(hits),n,confidence);
        budget = drdm.statistics.binomial_interval(sum(failures),n,confidence);
        passed = passed && coverage.one_sided_lower>=dataset.suite.minimum_joint_coverage && ...
            budget.one_sided_upper<=dataset.suite.target_budget_failure_probability;
    end
    reports(k) = struct('name',profiles(k).name,'sample_count',n,'false_paths',falseBound, ...
        'joint_coverage',coverage,'budget_failures',budget,'passed',passed, ...
        'incomplete_count',sum(arrayfun(@(r)~r.score.complete,records)), ...
        'missed_blocks',sum(arrayfun(@(r)r.score.missed_count>0,records)));
end
certificate = struct('kind','drdm-complete-pipeline-certificate-v1', ...
    'validated',calibration.usable && all([reports.passed]), ...
    'prepared_id',dataset.prepared_id,'procedure_id',dataset.procedure_id, ...
    'threshold',calibration.threshold,'interval_multiplier',dataset.description.options.interval_multiplier, ...
    'profiles',reports,'suite',dataset.suite,'suite_id',dataset.suite_id, ...
    'family_confidence',dataset.suite.family_confidence,'per_bound_confidence',confidence, ...
    'calibration_id',calibration.calibration_id,'evaluation_dataset_id',dataset.dataset_id, ...
    'evaluation_seeds',dataset.all_seeds, ...
    'scope','Only the declared randomized simulation populations; simultaneous per-profile average bounds, not worst-case or measured-data validation.');
certificate.certificate_id = drdm.statistics.fingerprint(certificate);
end
