function calibration = calibrate_weak_search(training,evaluation,targetProbability,familyConfidence)
%CALIBRATE_WEAK_SEARCH 训练一轮弱径完整搜索门限并独立评价。
%
% 输入：training、evaluation：同一强径零假设总体的独立 trials；targetProbability：目标事件概率；familyConfidence：总体置信水平。
% 输出：calibration：门限、训练容忍限、评价概率上界、事件计数及 validated。
%
% 控制新增弱径、错误强径或求解未完成的联合事件；训练与评价各分配一半显著性水平。

assert(strcmp(training.kind,'drdm-weak-trials-v1') && strcmp(evaluation.kind,training.kind) && ...
    strcmp(training.procedure_id,evaluation.procedure_id) && strcmp(training.code,evaluation.code) && ...
    isequaln(training.population,evaluation.population) && isequal(training.tolerances,evaluation.tolerances), ...
    'drdm:CalibrationMismatch','Training and evaluation must use the same frozen null population and procedure.');
drdm.statistics.check_seed_sets(training.seeds(:),evaluation.seeds(:));
validateattributes(targetProbability,{'numeric'},{'scalar','real','>',0,'<',1});
validateattributes(familyConfidence,{'numeric'},{'scalar','real','>',0,'<',1});
confidence = 1-(1-familyConfidence)/2;
bound = drdm.statistics.tolerance_limit([training.records.statistic],targetProbability,confidence);
threshold = bound.limit;
records = evaluation.records;
failed = ~[records.complete] | [records.strong_false];
events = failed | [records.statistic]>threshold;
interval = drdm.statistics.binomial_interval(sum(events),numel(events),confidence);
calibration = struct('kind','drdm-weak-search-calibration-v1', ...
    'procedure_id',training.procedure_id,'prepared_id',training.prepared_id,'code',training.code, ...
    'population',training.population,'tolerances',training.tolerances, ...
    'training_id',training.id,'evaluation_id',evaluation.id, ...
    'training_seeds',training.seeds,'evaluation_seeds',evaluation.seeds, ...
    'threshold',threshold,'target_probability',targetProbability,'family_confidence',familyConfidence, ...
    'training_bound',bound,'evaluation_interval',interval, ...
    'evaluation_incomplete_count',sum(~[records.complete]), ...
    'evaluation_false_strong_count',sum([records.strong_false]), ...
    'evaluation_weak_event_count',sum(~failed & [records.statistic]>threshold), ...
    'validated',isfinite(threshold) && interval.one_sided_upper<=targetProbability, ...
    'scope','One added path per CPI; declared null population and frozen full search only.');
calibration.id = drdm.statistics.fingerprint(calibration);
end
