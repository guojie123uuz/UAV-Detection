function evaluation = evaluate_threshold(calibration,trials,confidence)
%EVALUATE_THRESHOLD 用独立样本评价单轮门限的错误概率。
%
% 输入：calibration：门限训练结果；trials：评价样本；confidence：可选置信水平。
% 输出：evaluation：事件计数、概率界及条件验收结果。
%
% 未完成搜索计入错误事件，并单独报告次数。

if nargin<3
    confidence = calibration.confidence;
end
assert(confidence>=calibration.confidence,'drdm:EvaluationConfidence', ...
    'Independent evaluation confidence must meet the declared calibration confidence.');
assert(strcmp(calibration.procedure_id,trials.procedure_id) && ...
    strcmp(calibration.context_id,trials.context_id),'drdm:CalibrationMismatch','Search procedures differ.');
drdm.statistics.check_seed_sets(calibration.payload_seeds,calibration.noise_seeds, ...
    trials.payload_seeds,trials.noise_seeds);
assert(numel(trials.statistics)>0 && numel(trials.complete)==numel(trials.statistics) && ...
    numel(trials.payload_seeds)==numel(trials.statistics) && numel(trials.noise_seeds)==numel(trials.statistics), ...
    'drdm:EvaluationSamples','Incomplete evaluation records.');
complete = all(trials.complete) && all(isfinite(trials.statistics));
% 搜索失败计入错误事件，用同一批完整样本计算概率上界。
errors = trials.statistics>calibration.threshold | ~trials.complete | ~isfinite(trials.statistics);
interval = drdm.statistics.binomial_interval(sum(errors),numel(errors),confidence);
validated = complete && isfinite(calibration.threshold) && ...
    strcmp(calibration.status,'conditional_threshold') && ...
    interval.one_sided_upper<=calibration.target_false_path_probability;
evaluation = struct('conditionally_validated',validated,'complete',complete,'interval',interval, ...
    'calibration_id',calibration.calibration_id, ...
    'failed_search_count',sum(~trials.complete | ~isfinite(trials.statistics)), ...
    'threshold_exceedance_count',sum(trials.complete & isfinite(trials.statistics) & trials.statistics>calibration.threshold), ...
    'procedure_id',trials.procedure_id,'context_id',trials.context_id, ...
    'payload_seeds',trials.payload_seeds,'noise_seeds',trials.noise_seeds, ...
    'scope',trials.scope,'full_pipeline_validated',false);
end
